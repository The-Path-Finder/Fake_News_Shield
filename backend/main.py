import math
import os
import sys
from pathlib import Path
from typing import Optional

import joblib
from fastapi import FastAPI, HTTPException
from fastapi.middleware.cors import CORSMiddleware
from pydantic import BaseModel, Field

# Ensure project root is on sys.path so preprocessing & .pkl files resolve cleanly
BASE_DIR = Path(__file__).resolve().parent.parent
if str(BASE_DIR) not in sys.path:
    sys.path.insert(0, str(BASE_DIR))

from preprocessing import preprocess_multilingual  # noqa: E402

MODEL_PATH = BASE_DIR / "linear_svm_model.pkl"
VECTORIZER_PATH = BASE_DIR / "tfidf_vectorizer.pkl"

CONFIDENCE_THRESHOLD = 0.62
MIN_MATCHED_FEATURES = 2

TRUSTED_SOURCES = [
    {"name": "Reuters", "url": "https://www.reuters.com"},
    {"name": "Associated Press (AP)", "url": "https://apnews.com"},
    {"name": "BBC News", "url": "https://www.bbc.com/news"},
    {"name": "PIB Fact Check", "url": "https://factcheck.pib.gov.in"},
    {"name": "Alt News", "url": "https://www.altnews.in"},
]

DISCLAIMER = (
    "Predictions are generated by an automated NLP/ML model (TF-IDF + Linear SVM) "
    "and are NOT verified fact-checks. Always cross-check important claims with trusted sources."
)

app = FastAPI(
    title="Fake News Shield API",
    description=(
        "Real-Time Multilingual Misinformation & Fake News Shield FastAPI backend. "
        "Classifies news articles as Likely Real, Likely Fake, or Low Confidence."
    ),
    version="1.0.0",
)

app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],
    allow_credentials=False,
    allow_methods=["*"],
    allow_headers=["*"],
)

model = joblib.load(MODEL_PATH)
tfidf = joblib.load(VECTORIZER_PATH)


class PredictRequest(BaseModel):
    text: str = Field(..., min_length=1, description="News article text to analyze")
    url: Optional[str] = Field(None, description="Optional source URL of the article")
    source: Optional[str] = Field("web", description="Client source: web | chrome-extension | api")


class PredictResponse(BaseModel):
    label: str
    prediction_code: Optional[int]
    confidence: float
    raw_score: Optional[float]
    risk_level: str
    language: str
    language_name: str
    token_count: int
    matched_features: int
    cleaned_preview: str
    recommendation: str
    disclaimer: str
    trusted_sources: list[dict[str, str]]
    url: Optional[str] = None


@app.get("/health")
def health_check():
    return {
        "status": "ok",
        "model_loaded": model is not None and tfidf is not None,
        "model_type": type(model).__name__,
        "vocab_size": len(getattr(tfidf, "vocabulary_", {})),
    }


@app.get("/model-info")
def model_info():
    return {
        "project": "Real-Time Multilingual Misinformation & Fake News Shield",
        "team": "Hallucination Handlers",
        "active_classifier": "Linear SVM (LinearSVC)",
        "compared_classifiers": [
            "Logistic Regression (Baseline)",
            "Multinomial Naive Bayes",
            "Linear SVM (Selected)",
        ],
        "feature_extraction": {
            "method": "TF-IDF Vectorizer",
            "ngram_range": list(getattr(tfidf, "ngram_range", (1, 2))),
            "vocab_size": len(getattr(tfidf, "vocabulary_", {})),
        },
        "confidence_threshold": CONFIDENCE_THRESHOLD,
        "supported_languages": ["English (full classification)", "Hindi & Multilingual (detection + low-confidence verification flag)"],
        "disclaimer": DISCLAIMER,
    }


@app.post("/predict", response_model=PredictResponse)
def predict_news(payload: PredictRequest):
    raw_text = payload.text.strip()
    if not raw_text:
        raise HTTPException(status_code=400, detail="Please provide non-empty news text.")

    prep = preprocess_multilingual(raw_text)
    model_input = prep["model_input_text"]
    cleaned_display = prep["cleaned_text"]

    if not cleaned_display:
        raise HTTPException(
            status_code=400,
            detail="No meaningful text found after NLP preprocessing.",
        )

    # Transform using the trained TF-IDF vectorizer
    transformed = tfidf.transform([model_input]) if model_input else None
    matched_features = int(transformed.nnz) if transformed is not None else 0

    # If the article is non-English with minimal English vocabulary overlap,
    # or has too few matched TF-IDF features, flag as Low Confidence per PDF pipeline.
    if transformed is None or matched_features < MIN_MATCHED_FEATURES:
        if prep["language"] != "en":
            recommendation = (
                f"Detected {prep['language_name']} text. The deployed TF-IDF + Linear SVM model "
                "was trained primarily on English news corpora; insufficient English vocabulary "
                "overlap was found. Recommend manual verification with trusted regional & fact-check sources."
            )
        else:
            recommendation = (
                "Too few recognizable news terms were matched in the TF-IDF vocabulary. "
                "Provide a longer article excerpt or cross-check with trusted sources."
            )

        return PredictResponse(
            label="Low Confidence",
            prediction_code=None,
            confidence=0.5,
            raw_score=None,
            risk_level="uncertain",
            language=prep["language"],
            language_name=prep["language_name"],
            token_count=prep["token_count"],
            matched_features=matched_features,
            cleaned_preview=cleaned_display[:220],
            recommendation=recommendation,
            disclaimer=DISCLAIMER,
            trusted_sources=TRUSTED_SOURCES,
            url=payload.url,
        )

    prediction_code = int(model.predict(transformed)[0])

    if hasattr(model, "decision_function"):
        raw_score = float(model.decision_function(transformed)[0])
        # Convert SVM margin to [0, 1] probability-like confidence via logistic sigmoid
        prob_real = 1.0 / (1.0 + math.exp(-raw_score))
        confidence = max(prob_real, 1.0 - prob_real)
    elif hasattr(model, "predict_proba"):
        probs = model.predict_proba(transformed)[0]
        raw_score = float(probs[1] - probs[0])
        confidence = float(max(probs))
    else:
        raw_score = 1.0 if prediction_code == 1 else -1.0
        confidence = 0.75

    confidence = round(confidence, 4)

    # Confidence threshold check (Page 4 of PDF)
    if confidence < CONFIDENCE_THRESHOLD or (prep["language"] != "en" and matched_features < 5):
        label = "Low Confidence"
        risk_level = "uncertain"
        recommendation = (
            "Prediction confidence is below the reliability threshold. "
            "Recommend user review and verification against trusted news sources."
        )
    elif prediction_code == 1:
        label = "Likely Real"
        risk_level = "low"
        recommendation = (
            "Lower misinformation risk detected. As a best practice, still verify "
            "important claims with independent trusted sources."
        )
    else:
        label = "Likely Fake"
        risk_level = "high"
        recommendation = (
            "Warning: Linguistic and TF-IDF patterns resemble misinformation in training data. "
            "Cross-check this story with trusted fact-checking organizations before sharing."
        )

    return PredictResponse(
        label=label,
        prediction_code=prediction_code,
        confidence=confidence,
        raw_score=round(raw_score, 4),
        risk_level=risk_level,
        language=prep["language"],
        language_name=prep["language_name"],
        token_count=prep["token_count"],
        matched_features=matched_features,
        cleaned_preview=cleaned_display[:220],
        recommendation=recommendation,
        disclaimer=DISCLAIMER,
        trusted_sources=TRUSTED_SOURCES,
        url=payload.url,
    )

